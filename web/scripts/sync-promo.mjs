#!/usr/bin/env node
/**
 * Copies the studio promo (docs/promo) into web/public/promo with content-hashed filenames and
 * regenerates src/components/media/promo/promo-assets.ts. Re-run whenever docs/promo/*.mp4 or the
 * covers change (e.g. after the soundtrack is added), then rebuild/redeploy:
 *   node scripts/sync-promo.mjs
 * Hashed names make `Cache-Control: immutable` safe: a new file → a new URL.
 * Covers: WebP (q85) + the original JPG as fallback. Duration/audio read with ffprobe when present.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.resolve(WEB, "../docs/promo");
const OUT = path.join(WEB, "public/promo");
const TS = path.join(WEB, "src/components/media/promo/promo-assets.ts");

const sha = (buf) => createHash("sha256").update(buf).digest("hex");

function probe(file) {
  try {
    const out = execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration:stream=codec_type,width,height", "-of", "json", file], { encoding: "utf8" });
    const j = JSON.parse(out);
    const v = j.streams.find((s) => s.codec_type === "video");
    return { duration: Number(j.format.duration), hasAudio: j.streams.some((s) => s.codec_type === "audio"), width: v?.width, height: v?.height };
  } catch {
    return null;
  }
}

fs.mkdirSync(OUT, { recursive: true });
const keep = new Set();
const result = {};
const log = [];

for (const [key, base, w, h] of [
  ["landscape", "sultan-promo-1920x1080", 1920, 1080],
  ["portrait", "sultan-promo-1080x1920", 1080, 1920],
]) {
  const mp4Src = path.join(SRC, `${base}.mp4`);
  const jpgSrc = path.join(SRC, `${base}-cover.jpg`);
  const mp4 = fs.readFileSync(mp4Src);
  const jpg = fs.readFileSync(jpgSrc);
  const webp = await sharp(jpg).webp({ quality: 85 }).toBuffer();
  const hMp4 = sha(mp4);
  const hJpg = sha(jpg);
  const hWebp = sha(webp);
  const files = {
    video: [`${base}.${hMp4.slice(0, 8)}.mp4`, mp4, hMp4],
    coverJpg: [`${base}-cover.${hJpg.slice(0, 8)}.jpg`, jpg, hJpg],
    coverWebp: [`${base}-cover.${hWebp.slice(0, 8)}.webp`, webp, hWebp],
  };
  const entry = { width: w, height: h };
  for (const [k, [name, buf, hash]] of Object.entries(files)) {
    fs.writeFileSync(path.join(OUT, name), buf);
    keep.add(name);
    entry[k] = `/promo/${name}`;
    entry[`${k}Bytes`] = buf.length;
    log.push(`${hash}  ${String(buf.length).padStart(9)}  public/promo/${name}`);
  }
  const p = probe(mp4Src);
  entry.durationSeconds = p ? Math.round(p.duration) : 28;
  entry.hasAudio = p ? p.hasAudio : false;
  result[key] = entry;
}

// Remove stale hashed copies from earlier syncs.
for (const f of fs.readdirSync(OUT)) if (!keep.has(f)) fs.rmSync(path.join(OUT, f));

const ts = `// GENERATED by scripts/sync-promo.mjs — do not edit by hand. Re-run the script after docs/promo changes.
export type PromoAsset = {
  width: number;
  height: number;
  video: string;
  videoBytes: number;
  coverJpg: string;
  coverJpgBytes: number;
  coverWebp: string;
  coverWebpBytes: number;
  durationSeconds: number;
  hasAudio: boolean;
};

export const PROMO_ASSETS: { landscape: PromoAsset; portrait: PromoAsset } = ${JSON.stringify(result, null, 2)};
`;
fs.writeFileSync(TS, ts);

console.log(log.join("\n"));
const total = Object.values(result).reduce((a, e) => a + e.videoBytes + e.coverJpgBytes + e.coverWebpBytes, 0);
console.log(`total ${(total / 1048576).toFixed(2)} MiB; durations ${result.landscape.durationSeconds}s/${result.portrait.durationSeconds}s; audio ${result.landscape.hasAudio}/${result.portrait.hasAudio}`);
console.log(`wrote ${path.relative(WEB, TS)}`);
